'use strict';
const assert = require('assert/strict');
const fs = require('fs');
const os = require('os');
const path = require('path');
const { appendNarrativeProposals: append, reconcileNarrativeMemory: reconcile, activeNarrativeRecords: active,
    narrativePrompt, narrativeDigest: hash, correctedSourceIds } = require('../out/narrativeMemoryCore');
const user = { id: 'u1', role: 'user', content: 'ミナ、明日ここで風鈴を返すと約束する。' };
const gm = { id: 'turn-1', role: 'gm', content: 'ミナは約束を聞いて微笑んだ。納屋には縄が下がっている。' };
const state = { entries: [user, gm], world: { currentLocationId: 'harbor' }, commerce: { credits: 300 }, status: { location: '港' } };
const proposal = { kind: 'promise', npcId: 'mina', sourceRole: 'user', quote: user.content, content: 'ミナへ風鈴を返す', promisedBy: 'player' };
const add = (s = state, p = [proposal], mode = 'auto', turn = gm.id, action = user.content) => append(s, p, mode, { mina: 'ミナ' }, turn, action);
const original = JSON.stringify(state);
const memory = add();
assert.equal(memory.records.length, 1);
assert.equal(memory.records[0].person.id, 'npc:mina');
assert.equal(active(memory).length, 1);
assert.equal(JSON.stringify(state), original, 'no money, trust, time, or input mutation');
assert.equal(add({ ...state, narrativeMemory: memory }).records.length, 1, 'duplicate delivery is idempotent');
assert.equal(add(state, [proposal], 'review').records[0].approval, 'pending');
const reviewState = { ...state, narrativeMemory: add(state, [proposal], 'review') };
assert.equal(active(add(reviewState, [])).length, 0, 'switching to auto does not adopt pending');
assert.equal(narrativePrompt(reviewState, 'ミナ', 1500), '', 'pending never reaches GM');
assert.equal(add(state, [{ ...proposal, sourceRole: 'gm', quote: gm.content }]).records.length, 0, 'NPC request cannot commit player');
assert.equal(add(state, [{ ...proposal, quote: 'invented' }]).records.length, 0);
assert.equal(add(state, [null, {}, { ...proposal, kind: 'reward' }]).records.length, 0);
assert.equal(add(state, [proposal], 'auto', 'missing').records.length, 0, 'unaccepted/absent turn cannot record');
assert.equal(add(state, [proposal], 'auto', gm.id, 'different pending action').records.length, 0);
const ambiguous = add(state, [{ ...proposal, npcId: undefined, personName: 'ミナ' }]);
assert.equal(ambiguous.records[0].approval, 'pending');
assert.equal(ambiguous.records[0].needsIdentity, true, 'known NPC names require identity confirmation');
const stranger = add(state, [{ ...proposal, npcId: undefined, personName: '旅人' }]);
assert.ok(stranger.records[0].person.id.startsWith('story:'));
assert.equal(stranger.records[0].approval, 'accepted');
assert.equal(reconcile(memory, [user]).records.length, 0, 'Undo GM removes user-sourced promises too');
assert.equal(reconcile(memory, [{ ...user, content: '約束しない。' }, gm]).records[0].approval, 'pending');
assert.equal(reconcile(memory, [user, { ...gm, content: '訂正版' }]).records[0].approval, 'pending');
assert.equal(reconcile(undefined, state.entries).records.length, 0, 'old saves/checkpoints');
const g2 = { id: 'turn-2', role: 'gm', content: '港へ来た。' };
const correction = { ...memory.records[0], id: 'correction1', kind: 'correction', content: '納屋に下がるのは風鈴。', sourceId: gm.id, sourceHash: hash(gm.content), role: 'gm' };
const corrected = { ...state, narrativeMemory: { format: 1, records: [correction] } };
const edited = { ...correction, id: 'correction2', targetId: correction.id, content: '納屋に下がるのは青い風鈴。', anchorId: g2.id, anchorHash: hash(g2.content) };
const later = { ...corrected, entries: [...state.entries, g2], narrativeMemory: { format: 1, records: [correction, edited] } };
assert.deepEqual([...correctedSourceIds(later)], [gm.id], 'editing correction preserves target, not latest narration');
assert.deepEqual(active(reconcile(later.narrativeMemory, state.entries)).map(r => r.id), [correction.id], 'Undo update restores previous correction');
const update = { ...proposal, targetId: memory.records[0].id, status: 'fulfilled' };
const updated = add({ ...state, entries: [...state.entries, g2], narrativeMemory: memory }, [update], 'auto', g2.id);
assert.equal(active(updated)[0].status, 'fulfilled');
assert.equal(active(reconcile(updated, state.entries))[0].status, 'open', 'Undo fulfillment restores unresolved promise');
const twenty = { ...state, entries: [...state.entries, ...Array.from({ length: 20 }, (_, i) => ({ id: 'later-' + i, role: 'gm', content: '別の旅 ' + i }))], narrativeMemory: memory };
assert.match(narrativePrompt(twenty, 'ミナと再会', 1000), /ミナへ風鈴を返す/);
assert.ok(narrativePrompt(twenty, 'ミナと再会', 250).length <= 250);
const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'lr-memory-'));
try {
    fs.writeFileSync(path.join(temp, 'game_state.json'), JSON.stringify(later));
    const reopened = JSON.parse(fs.readFileSync(path.join(temp, 'game_state.json')));
    assert.match(narrativePrompt(reopened, '納屋', 1500), /青い風鈴/);
    assert.deepEqual([...correctedSourceIds(reopened)], [gm.id]);
    assert.deepEqual(reconcile(reopened.narrativeMemory, reopened.entries), later.narrativeMemory, 'full snapshot roundtrip');
} finally { fs.rmSync(temp, { recursive: true, force: true }); }
console.log('PASS narrative memory: adoption, evidence, identity, idempotency, Undo, edit, snapshot, reunion budget');
